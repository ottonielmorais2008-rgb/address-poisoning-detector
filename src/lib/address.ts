const ADDRESS_RE = /^0x[0-9a-fA-F]{40}$/;

export function isAddress(value: string): boolean {
  return ADDRESS_RE.test(value.trim());
}

export function normalizeAddress(value: string): string | null {
  const trimmed = value.trim();
  return isAddress(trimmed) ? trimmed.toLowerCase() : null;
}

/** Number of equal hex characters at the start of two addresses (ignoring 0x and case). */
export function commonPrefix(a: string, b: string): number {
  const x = a.slice(2).toLowerCase();
  const y = b.slice(2).toLowerCase();
  let i = 0;
  while (i < x.length && i < y.length && x[i] === y[i]) i++;
  return i;
}

/** Number of equal hex characters at the end of two addresses (ignoring case). */
export function commonSuffix(a: string, b: string): number {
  const x = a.slice(2).toLowerCase();
  const y = b.slice(2).toLowerCase();
  let i = 0;
  while (i < x.length && i < y.length && x[x.length - 1 - i] === y[y.length - 1 - i]) i++;
  return i;
}

export const MIN_PREFIX = 3;
export const MIN_SUFFIX = 3;
export const MIN_TOTAL = 7;

/**
 * Two different addresses "look alike" when they share enough leading and trailing
 * characters that a wallet showing a shortened form (0x1234…abcd) would make them
 * look identical: at least 3 + 3 and 7 in total, or 2 on one side and 8 in total.
 * Random pairs match 7+ characters about once in 268 million tries,
 * so a match is almost always deliberate (a vanity address generated by an attacker).
 */
export function looksAlike(a: string, b: string): { prefix: number; suffix: number } | null {
  if (a.toLowerCase() === b.toLowerCase()) return null;
  const prefix = commonPrefix(a, b);
  const suffix = commonSuffix(a, b);
  const total = prefix + suffix;
  const balanced = prefix >= MIN_PREFIX && suffix >= MIN_SUFFIX && total >= MIN_TOTAL;
  // Some attackers only copy 2 leading characters but more trailing ones (or the reverse).
  const lopsided = Math.min(prefix, suffix) >= 2 && total >= MIN_TOTAL + 1;
  if (balanced || lopsided) return { prefix, suffix };
  return null;
}

export function shortAddress(address: string, head = 6, tail = 4): string {
  if (address.length <= head + tail + 2) return address;
  return `${address.slice(0, head)}…${address.slice(-tail)}`;
}
